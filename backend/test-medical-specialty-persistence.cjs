assert.equal(invoke('listAudiology', {}, { patientId: 'medical-patient' }).code, 403);
db.prepare("INSERT INTO user_medical_specialties (user_id, medical_specialty_id, tenant_id) VALUES ('doctor', 'med-spec-otorrino', 'test-medical')").run();
assert.equal(invoke('listAudiology', {}, { patientId: 'medical-patient' }).code, 200);
assert.equal(invoke('saveAudiology', { patientId: 'medical-patient', examType: 'clinical', results: { schemaVersion: 2 } }).code, 201);
assert.equal(invoke('saveIdv10', { patientId: 'medical-patient', answers: Array(10).fill(0), totalScore: 0 }).code, 201);
assert.equal(invoke('saveIdv10', { patientId: 'other-patient', answers: Array(10).fill(0), totalScore: 0 }).code, 403);
assert.equal(invoke('getIdv10List', {}, { patientId: 'medical-patient' }).code, 200);
const catalog = MedicalTreeService.getMedicalTree().specialties;
assert.equal(catalog.length, 15);
const before = catalog.map(s => [s.id, s.slug]);
const notes = Object.fromEntries(MEDICAL_NOTE_KEYS.map(key => [key, { finding: key, nested: { zero: 0 }, values: [] }]));
notes.dermatoNotes = { lesions: [{ id: 'lesion-1', identification: 'Lesão A', photo: { fileId: 'file-reference' }, evolution: 'estável' }] };
notes.sharedAssessments = { regional: { shoulder: { strength_json: [{ grade: '3' }] } }, scales: [{ scaleName: 'Teste', score: '0' }], adl: [], anthropometry: { weight: '15', measures: { 'Perímetro cefálico': { cm: '45' } } } };
const draft = invoke('saveDraft', { moduleType: 'medical', patientId: 'medical-patient', draftData: notes, clientUpdatedAt: new Date().toISOString() });
assert.equal(draft.code, 200, JSON.stringify(draft.data));
const recovered = invoke('getDraft', {}, { moduleType: 'medical', patientId: 'medical-patient' });
assert.equal(recovered.code, 200);
assert.deepEqual(recovered.data.draft.draftData, notes);
assert.equal(invoke('getDraft', {}, { moduleType: 'medical', patientId: 'medical-patient' }, 'other-medical').code, 403);
for (const specialty of catalog) {
  const payload = { patientId: 'medical-patient', specialtyPreset: specialty.slug, chiefComplaint: 'Queixa', pastMedicalHistory: 'Antecedentes', familyHistory: 'Família', habitsLifestyle: 'Hábitos', vitalSigns: { weight: 60 }, conducts: 'Retorno', ...notes };
  const finished = invoke('finishConsultation', payload);
  assert.equal(finished.code, 201, JSON.stringify(finished.data));
  const stored = db.prepare('SELECT * FROM records WHERE id = ?').get(finished.data.recordId);
  const parsed = JSON.parse(stored.technical_notes);
  for (const key of MEDICAL_NOTE_KEYS) assert.deepEqual(parsed[key], notes[key]);
  assert.equal(parsed.pastMedicalHistory, 'Antecedentes');
  assert.equal(stored.is_sealed, 1);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM clinical_drafts WHERE tenant_id = 'test-medical' AND patient_id = 'medical-patient' AND module_type = 'medical'").get().count, 0);
  const reopened = invoke('getConsultationById', {}, { id: finished.data.recordId });
  assert.equal(reopened.code, 200);
  assert.deepEqual(reopened.data.specialtyNotes.dermatoNotes, notes.dermatoNotes);
  assert.equal(invoke('getConsultationById', {}, { id: finished.data.recordId }, 'other-medical').code, 404);
}
