const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'zemda-medical-'));
process.env.DATABASE_PATH = path.join(dir, 'medical.sqlite');
process.env.NODE_ENV = 'test';
const { db, initializeDatabase } = require('./dist/config/database');
initializeDatabase();
const { MedicalController } = require('./dist/controllers/medical.controller');
const { ClinicalDraftController } = require('./dist/controllers/clinical-draft.controller');
const { SpeechTherapyController } = require('./dist/controllers/speech-therapy.controller');
const { medicalObject, MEDICAL_NOTE_KEYS } = require('./dist/services/medical-payload');
const { MedicalTreeService } = require('./dist/services/medical-tree.service');
const invoke = (method, body = {}, params = {}, tenantId = 'test-medical') => {
  const req = { body, params, query: {}, tenantId, user: { userId: 'doctor', role: 'professional', name: 'Doctor' }, headers: {}, ip: '127.0.0.1' };
  const res = { code: 200, data: null, status(code) { this.code = code; return this; }, json(data) { this.data = data; return this; } };
  (MedicalController[method] || SpeechTherapyController[method] || ClinicalDraftController[method])(req, res);
  return res;
};
db.prepare("INSERT INTO tenants (id, slug, name, cnpj_cpf, email, status) VALUES ('test-medical', 'test-medical', 'Test', '111', 'medical@test.local', 'active')").run();
