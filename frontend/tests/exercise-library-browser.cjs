const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { DEFAULT_EXERCISE_LIBRARY } = require('../../backend/dist/config/exercise-library.seed');
const photos = require('../../backend/src/config/exercise-library.photos.json');
const { matchesExercise } = require('../../backend/dist/services/personal-exercise-utils');
const { exerciseAnimation } = require('../../backend/dist/services/exercise-media');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5173';
const out = process.env.TEST_OUTPUT_DIR || path.join(__dirname, 'results');
fs.mkdirSync(out, { recursive:true });
async function main() {
  const browser = await chromium.launch({ headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {}) });
  try {
    const page = await browser.newPage({ viewport:{ width:1440, height:1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    let catalog = DEFAULT_EXERCISE_LIBRARY.map(ex => ({...ex, ...exerciseAnimation({...ex,tenant_id:'global',is_custom:0}), is_active:1, is_custom:0, image_attribution_json:JSON.stringify(photos.find(photo => photo.photo_url === ex.photo_url) || null), secondary_muscles_json:JSON.stringify(ex.secondary_muscles)}));
    let workout = null;
    let imageRequests = 0;
    await page.route('**/*', async route => {
      const url = new URL(route.request().url());
      if (url.origin !== base) return route.abort();
      if (url.pathname.startsWith('/exercise-fallbacks/')) { imageRequests++; return route.continue(); }
      if (!url.pathname.startsWith('/api/')) return route.continue();
      let data = {};
      const body = route.request().headers()['content-type']?.includes('application/json') ? route.request().postDataJSON() : null;
      if (url.pathname.endsWith('/personal/exercises')) {
        if (route.request().method() === 'POST') { const ex = {...body,id:'custom-browser',is_custom:1,is_active:1}; catalog.push(ex); data={id:ex.id,exercise:ex}; }
        else data = {exercises:catalog.filter(ex => matchesExercise(ex, Object.fromEntries(url.searchParams)))};
      } else if (url.pathname.endsWith('/personal/exercises/custom-browser')) { Object.assign(catalog.find(ex => ex.id === 'custom-browser'),body); data={exercise:catalog.find(ex => ex.id === 'custom-browser')}; }
      else if (url.pathname.endsWith('/personal/workouts')) { workout = {...body,id:'workout-browser'}; data={id:workout.id}; }
      else if (url.pathname.endsWith('/workouts/workout-browser')) data={workout,exercises:workout.exercises};
      else if (url.pathname.endsWith('/clinics/current')) data={name:'Clínica de Teste',id:'test-clinic'};
      else if (url.pathname.endsWith('/url')) data={url:`${base}/exercise-fallbacks/ex-supino-reto-barra.webp`,expiresIn:300};
      else if (url.pathname.endsWith('/upload-ticket')) data={uploadUrl:`${base}/api/test-worker/upload`,uploadToken:'local-test-double',objectKey:'clinics/test/exercises/photo.webp'};
      else if (url.pathname.endsWith('/test-worker/upload')) data={ok:true,objectKey:'clinics/test/exercises/photo.webp'};
      else if (url.pathname.endsWith('/files/complete')) data={success:true,file:{id:'att-browser-test',objectKey:'clinics/test/exercises/photo.webp',mimeType:'image/webp',fileSize:100}};
      return route.fulfill({json:data});
    });
    await page.goto(`${base}/tests/exercise-library.html`);
    await page.getByText('268 exercícios encontrados').waitFor();
    await page.waitForFunction(() => document.querySelectorAll('img').length > 0 && [...document.images].some(img => img.complete && img.naturalWidth > 0));
    assert(imageRequests < 80, `Lazy loading should not fetch all 268 images: ${imageRequests}`);
    console.log('PASS library, original items and lazy loading', imageRequests);
    await page.getByRole('button',{name:'Alongamentos',exact:true}).click();
    await page.getByText('48 exercícios encontrados').waitFor();
    await page.waitForFunction(() => [...document.images].filter(img => img.getBoundingClientRect().top < innerHeight).length > 0 && [...document.images].filter(img => img.getBoundingClientRect().top < innerHeight).every(img => img.complete && img.naturalWidth > 0));
    await page.screenshot({path:path.join(out,'alongamentos.png')});
    await page.getByRole('button',{name:'Mobilidade',exact:true}).click();
    await page.getByText('25 exercícios encontrados').waitFor();
    await page.getByRole('button',{name:'Todos os Músculos',exact:true}).click();
    const search = page.locator('input[type="text"]').first();
    await search.fill('Supino Reto com Barra'); await search.press('Enter');
    await page.getByText('1 exercícios encontrados').waitFor();
    await page.getByRole('button',{name:'Ver detalhes',exact:true}).click();
    await page.getByText('Notas Técnicas & Cuidados').waitFor();
    await page.locator('img[src^="/exercise-photos/"]').last().waitFor();
    await page.waitForFunction(() => [...document.images].filter(img => img.src.includes('/exercise-photos/')).every(img => img.complete && img.naturalWidth > 0));
    await page.getByText(/U.S. Army/).waitFor();
    await page.screenshot({path:path.join(out,'detalhes.png')});
    await page.reload();
    await page.getByText('268 exercícios encontrados').waitFor();
    console.log('PASS stretch/mobility/search/detail/F5');
    await page.getByRole('button',{name:'Criar Exercício',exact:true}).click();
    await page.getByPlaceholder('Ex: Supino Inclinado com Halteres').fill('Teste de upload próprio');
    await page.locator('input[type="file"]').setInputFiles(path.resolve(__dirname,'../public/exercise-fallbacks/ex-supino-reto-barra.webp'));
    await page.getByText('Upload concluído.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Cadastrar Exercício',exact:true}).click();
    await page.getByText('269 exercícios encontrados').waitFor();
    assert.equal(catalog.find(ex => ex.id === 'custom-browser').exercise_file_id,'att-browser-test');
    await page.reload();
    const customSearch = page.locator('input[type="text"]').first();
    await customSearch.fill('Teste de upload próprio'); await customSearch.press('Enter');
    await page.getByText('1 exercícios encontrados').waitFor();
    await page.waitForFunction(() => [...document.images].some(img => img.complete && img.naturalWidth > 0));
    await page.getByRole('button',{name:'Editar exercício',exact:true}).click();
    await page.locator('input[type="file"]').setInputFiles(path.resolve(__dirname,'../public/exercise-fallbacks/ex-dead-bug.webp'));
    await page.getByText('Upload concluído.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Salvar Alterações',exact:true}).click();
    await page.reload();
    console.log('PASS upload and photo replacement across reload (HTTP/Worker test doubles)');
    await page.goto(`${base}/tests/exercise-library.html?mode=builder`);
    await page.getByRole('button',{name:/biblioteca/i}).click();
    await page.getByRole('button',{name:'Alongamentos',exact:true}).click();
    await page.getByText('48 exercícios encontrados').waitFor();
    await page.getByRole('button',{name:'Selecionar',exact:true}).first().click();
    await page.getByLabel('Duração em segundos').fill('25');
    await page.getByLabel('Lado', {exact:true}).selectOption('ambos');
    await page.screenshot({path:path.join(out,'treino.png')});
    await page.getByRole('button',{name:/salvar/i}).click();
    await page.getByRole('status').waitFor();
    assert.equal(workout.exercises[0].duration_seconds,25);
    assert.equal(workout.exercises[0].side,'ambos');
    assert(workout.exercises[0].photo_url.startsWith('/exercise-fallbacks/'));
    assert.equal(workout.exercises[0].load_kg,undefined);
    workout.exercises.push({...catalog.find(ex => ex.id === 'ex-supino-reto-barra'),exercise_id:'ex-supino-reto-barra',sets:3,reps:'10'});
    await page.evaluate(value => localStorage.setItem('test-workout',JSON.stringify(value)),workout);
    await page.reload(); await page.getByLabel('Duração em segundos').first().waitFor();
    assert.equal(await page.getByLabel('Duração em segundos').first().inputValue(),'25');
    await page.locator('img[src^="/exercise-photos/"]').waitFor();
    await page.screenshot({path:path.join(out,'treino-com-foto.png')});
    console.log('PASS builder duration, side, persistence and reload');
    await page.goto(`${base}/tests/exercise-library.html?mode=pdf`);
    await page.getByText('25s • ambos').waitFor();
    await page.getByRole('button',{name:'Imprimir / Salvar em PDF',exact:true}).waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent.includes('Imprimir / Salvar em PDF') && !button.disabled));
    await page.evaluate(() => { window.print = () => { window.__printed = true; }; });
    await page.getByRole('button',{name:'Imprimir / Salvar em PDF',exact:true}).click();
    await page.waitForFunction(() => window.__printed === true);
    await page.waitForFunction(() => [...document.images].every(img => img.complete));
    assert(await page.locator('img[src^="/exercise-photos/"]').count() > 0);
    await page.getByText(/U.S. Army/).waitFor();
    await page.screenshot({path:path.join(out,'pdf-com-imagens.png')});
    await page.pdf({path:path.join(out,'treino-com-imagens.pdf'),format:'A4',printBackground:true});
    await page.getByRole('button',{name:'PDF compacto sem imagens'}).click();
    assert.equal(await page.locator('img').count(),0);
    await page.screenshot({path:path.join(out,'pdf-compacto.png')});
    await page.pdf({path:path.join(out,'treino-compacto.pdf'),format:'A4',printBackground:true});
    await page.emulateMedia({media:'print'});
    await page.screenshot({path:path.join(out,'impressao-compacta.png'),fullPage:true});
    console.log('PASS PDF with images and compact without images');
    assert.deepEqual(errors,[]);
  } finally { await browser.close(); }
}
main().catch(err => { console.error(err); process.exitCode=1; });
